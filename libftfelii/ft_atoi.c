#include "libft.h"

int	ft_atoi(const char *nptr)
{
	int				i;
	int				res;
	int				a;
	unsigned int	nb;

	res = 0;
	a = 1;
	i = 0;
	nb = 0;
	while ((nptr[i] == ' ') || (nptr[i] >= 9 && nptr[i] <= 13))
		i++;
	if (nptr[i] == '-' || nptr[i] == '+')
	{
		if (nptr[i] == '-')
			a = -a;
		i++;
	}
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		nb = nb * 10 + (nptr[i] - 48);
		i++;
	}
	res = nb * a;
	return (res);
}
